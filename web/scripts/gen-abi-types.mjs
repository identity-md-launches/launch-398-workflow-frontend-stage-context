// Generates src/generated/abis.ts from the implementation-derived ABI exports in docs/abi.
// The generated constants exist only so TypeScript can infer contract call types. At runtime the
// app loads the ABI JSON referenced by dist/imd-deployment.json and refuses to start if its
// canonical hash differs from these constants or from the manifest.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { abiSourceDir, canonicalKeccak, loadHandoff, webRoot } from './lib.mjs';

const { handoff } = loadHandoff();
const lowerFirst = (s) => s[0].toLowerCase() + s.slice(1);

let out = '// Generated by scripts/gen-abi-types.mjs from ../../docs/abi/*.json. Do not edit by hand.\n';
out += '// Used for TypeScript inference only; the runtime ABI comes from dist/imd-deployment.json.\n\n';
for (const contract of handoff.contracts) {
  const abi = JSON.parse(readFileSync(resolve(abiSourceDir, `${contract.name}.json`), 'utf8'));
  const hash = canonicalKeccak(abi);
  if (hash !== contract.abiHash) {
    throw new Error(`ABI hash mismatch for ${contract.name}: docs/abi gives ${hash}, handoff expects ${contract.abiHash}`);
  }
  out += `export const ${lowerFirst(contract.name)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
out += `/** Block in which the handoff records the deployment; log queries start here. */\n`;
out += `export const deploymentBlock = ${Math.min(...handoff.contracts.map((c) => c.blockNumber))};\n`;

const target = resolve(webRoot, 'src', 'generated');
mkdirSync(target, { recursive: true });
writeFileSync(resolve(target, 'abis.ts'), out);
console.log(`wrote src/generated/abis.ts for ${handoff.contracts.map((c) => c.name).join(', ')}`);
